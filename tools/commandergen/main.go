// Command commandergen writes internal/cli/commander_flags.go from the
// TypeScript CLI's Commander tree, dumped by dump-commands.ts. It records,
// in kebab case, the option strings that differ from "--name <name>", the
// allowed choices of each option, and the argument parser each option uses,
// so that errors match the TypeScript CLI's wording and order.
//
// Usage: commandergen <typescript-commands.json> <commander_flags.go>
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"sort"
	"strings"
)

type command struct {
	Path    string `json:"path"`
	Options []struct {
		Flags      string   `json:"flags"`
		Long       string   `json:"long"`
		Short      string   `json:"short"`
		TakesValue bool     `json:"takesValue"`
		Choices    []string `json:"choices"`
		Parser     string   `json:"parser"`
	} `json:"options"`
}

var snakeName = regexp.MustCompile(`(--|<)([a-z0-9]+(?:_[a-z0-9]+)+)`)

func kebabNames(s string) string {
	return snakeName.ReplaceAllStringFunc(s, func(m string) string { return strings.ReplaceAll(m, "_", "-") })
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: commandergen <typescript-commands.json> <commander_flags.go>")
		os.Exit(2)
	}

	if err := run(os.Args[1], os.Args[2]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(input, output string) error {
	raw, err := os.ReadFile(input)
	if err != nil {
		return err
	}
	var commands []command
	if err := json.Unmarshal(raw, &commands); err != nil {
		return err
	}

	flags := map[string]string{}
	choices := map[string][]string{}
	parsers := map[string]string{}
	for _, c := range commands {
		path := strings.TrimSpace("prefactor " + strings.ReplaceAll(c.Path, "_", "-"))
		for _, o := range c.Options {
			if o.Long == "" || o.Long == "--version" {
				continue
			}
			long := kebabNames(o.Long)
			key := path + " " + long

			standard := long
			if o.Short != "" {
				standard = o.Short + ", " + standard
			}
			if o.TakesValue {
				standard += " <" + strings.TrimPrefix(long, "--") + ">"
			}
			if kebab := kebabNames(o.Flags); kebab != standard {
				flags[key] = kebab
			}
			if o.Choices != nil {
				choices[key] = o.Choices
			}
			if o.Parser != "" {
				parsers[key] = o.Parser
			}
		}
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/commandergen from testdata/typescript-commands.json. DO NOT EDIT.\n\npackage cli\n\n")
	b.WriteString("// commanderOptionFlags holds the TypeScript CLI's option strings, in kebab\n// case, where they differ from the default \"--name <name>\" form. Errors that\n// quote an option use them, as Commander does.\n")
	b.WriteString("var commanderOptionFlags = map[string]string{\n")
	for _, key := range sortedKeys(flags) {
		fmt.Fprintf(&b, "%q: %q,\n", key, flags[key])
	}
	b.WriteString("}\n\n")
	b.WriteString("// commanderOptionChoices holds the values each option allows, checked as\n// the option is read.\n")
	b.WriteString("var commanderOptionChoices = map[string][]string{\n")
	for _, key := range sortedKeys(choices) {
		fmt.Fprintf(&b, "%q: {", key)
		for i, choice := range choices[key] {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q", choice)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")
	b.WriteString("// commanderOptionParsers names the TypeScript argument parser of each\n// option, run as the option is read. optionParsers implements them.\n")
	b.WriteString("var commanderOptionParsers = map[string]string{\n")
	for _, key := range sortedKeys(parsers) {
		fmt.Fprintf(&b, "%q: %q,\n", key, parsers[key])
	}
	b.WriteString("}\n")

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(output, formatted, 0o644)
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for key := range m {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}
